#!/usr/bin/env node
/**
 * Summarise an evaluation run: node eval/report.js [run1]  →  eval/results/<run>.md
 *
 * Vulnerable set (known-vulnerable releases from GitHub advisories):
 *   caught         verdict is not PASS (the server would not be auto-listed)
 *   caught by a finding   a finding-based rule fired (hard fail or score threshold),
 *                  not only a coverage rule
 *   auto-rejected  verdict FAIL
 *   threat match   a finding (score ≥ 0.40) of the advisory's threat class
 *   localized      such a finding inside the code the security fix changed
 * Fixed twins: how the verdict moves from the vulnerable to the fixed release.
 * Benign set: false rejections (FAIL) and REVIEW load on popular servers.
 */

const fs = require('fs');
const path = require('path');

const run = process.argv[2] || 'run1';
const IN = path.join(__dirname, 'results', `${run}.jsonl`);
const OUT = path.join(__dirname, 'results', `${run}.md`);
const rows = fs.readFileSync(IN, 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l));

const FINDING_RULES = new Set(['ast_high_hard_fail', 'score_thresholds']);
const COVERAGE_RULES = new Set(['required_analyzer_unavailable', 'unpinned_analyzer_version', 'insufficient_code_coverage',
  'no_tools_discovered', 'source_not_fully_analysed', 'runtime_descriptions']);
const RANK = { PASS: 0, REVIEW: 1, FAIL: 2 };
const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(0)}%` : '—');
const median = xs => { const s = [...xs].sort((a, b) => a - b); return s.length ? s[Math.floor(s.length / 2)] : 0; };
const p95 = xs => { const s = [...xs].sort((a, b) => a - b); return s.length ? s[Math.min(s.length - 1, Math.floor(s.length * 0.95))] : 0; };

function raw(r) {
  return (r.slots || []).flatMap(s => s.findings.map(f => ({ ...f, slot: s.slot }))).filter(f => f.score >= 0.4);
}

function localized(r, f) {
  const changed = r.fix_changed_lines && r.fix_changed_lines[f.file];
  if (!changed || !f.file) return false;
  const lo = f.fn ? f.fn.start_line : f.line - 3;
  const hi = f.fn ? f.fn.end_line : f.line + 3;
  return changed.some(l => l >= lo && l <= hi);
}

function langOf(r) {
  const l = r.languages || [];
  if (l.includes('python') && l.some(x => x !== 'python')) return 'mixed';
  if (l.includes('python')) return 'python';
  if (l.length) return 'ts/js';
  return 'none';
}

const vuln = rows.filter(r => r.set === 'vuln' && r.version === 'vulnerable');
const fixed = new Map(rows.filter(r => r.set === 'vuln' && r.version === 'fixed').map(r => [r.id, r]));
const benign = rows.filter(r => r.set === 'benign');
const ok = r => r.ok;

const lines = [];
const out = s => lines.push(s);
out(`# Evaluation run \`${run}\``);
out('');
out(`Generated by \`eval/report.js\` from \`eval/results/${run}.jsonl\` (${rows.length} scans). Corpus: \`eval/corpus.json\` (GitHub advisories) and \`eval/benign.json\`.`);
out('');

// ── Vulnerable set ────────────────────────────────────────────────────────────
const V = vuln.filter(ok);
const caught = V.filter(r => r.verdict !== 'PASS');
const caughtByFinding = V.filter(r => r.reasons.some(x => FINDING_RULES.has(x.rule)));
const failed = V.filter(r => r.verdict === 'FAIL');
const matched = V.filter(r => raw(r).some(f => r.expected_threats.includes(f.threat)));
const withDiff = V.filter(r => r.fix_changed_lines && !r.fix_changed_lines.__error && Object.keys(r.fix_changed_lines).length);
const loc = withDiff.filter(r => raw(r).some(f => localized(r, f)));
const locMatched = withDiff.filter(r => raw(r).some(f => localized(r, f) && r.expected_threats.includes(f.threat)));

out('## 1. Known-vulnerable releases');
out('');
out(`${vuln.length} releases scanned at the last vulnerable tag (${vuln.length - V.length} could not be ingested).`);
out('');
out('| Metric | Result |');
out('|---|---|');
out(`| Caught (not PASS: would not be auto-listed) | **${caught.length}/${V.length} (${pct(caught.length, V.length)})** |`);
out(`| … caught by a finding (not only a coverage rule) | ${caughtByFinding.length}/${V.length} (${pct(caughtByFinding.length, V.length)}) |`);
out(`| Auto-rejected (FAIL) | ${failed.length}/${V.length} (${pct(failed.length, V.length)}) |`);
out(`| A finding of the advisory's threat class | ${matched.length}/${V.length} (${pct(matched.length, V.length)}) |`);
out(`| A finding inside the code the fix changed (any threat) | ${loc.length}/${withDiff.length} (${pct(loc.length, withDiff.length)}) |`);
out(`| … of the advisory's threat class | ${locMatched.length}/${withDiff.length} (${pct(locMatched.length, withDiff.length)}) |`);
out('');

out('### By threat class (advisory CWE)');
out('');
out('| Threat | Releases | Caught | Caught by finding | FAIL | Threat match |');
out('|---|---|---|---|---|---|');
for (const t of [...new Set(V.flatMap(r => r.expected_threats))].sort()) {
  const g = V.filter(r => r.expected_threats.includes(t));
  out(`| ${t} | ${g.length} | ${pct(g.filter(r => r.verdict !== 'PASS').length, g.length)} | ${pct(g.filter(r => r.reasons.some(x => FINDING_RULES.has(x.rule))).length, g.length)} | ${pct(g.filter(r => r.verdict === 'FAIL').length, g.length)} | ${pct(g.filter(r => raw(r).some(f => f.threat === t)).length, g.length)} |`);
}
out('');

out('### By language');
out('');
out('| Language | Releases | Caught | Caught by finding | FAIL |');
out('|---|---|---|---|---|');
for (const l of ['python', 'ts/js', 'mixed', 'none']) {
  const g = V.filter(r => langOf(r) === l);
  if (!g.length) continue;
  out(`| ${l} | ${g.length} | ${pct(g.filter(r => r.verdict !== 'PASS').length, g.length)} | ${pct(g.filter(r => r.reasons.some(x => FINDING_RULES.has(x.rule))).length, g.length)} | ${pct(g.filter(r => r.verdict === 'FAIL').length, g.length)} |`);
}
out('');

out('### Which analyzer found the localized, threat-matched issue');
out('');
const bySlot = {};
for (const r of withDiff) {
  const slots = new Set(raw(r).filter(f => localized(r, f) && r.expected_threats.includes(f.threat)).map(f => f.slot));
  for (const s of slots) bySlot[s] = (bySlot[s] || 0) + 1;
}
out(Object.keys(bySlot).length ? Object.entries(bySlot).map(([s, n]) => `- ${s}: ${n}/${withDiff.length}`).join('\n') : '- none');
out('');

// ── Fixed twins ───────────────────────────────────────────────────────────────
const pairs = V.filter(r => fixed.has(r.id) && fixed.get(r.id).ok).map(r => [r, fixed.get(r.id)]);
const trans = {};
for (const [a, b] of pairs) trans[`${a.verdict} → ${b.verdict}`] = (trans[`${a.verdict} → ${b.verdict}`] || 0) + 1;
const better = pairs.filter(([a, b]) => RANK[b.verdict] < RANK[a.verdict]).length;
const worse = pairs.filter(([a, b]) => RANK[b.verdict] > RANK[a.verdict]).length;
const locGone = pairs.filter(([a, b]) => {
  const l = raw(a).filter(f => localized(a, f) && a.expected_threats.includes(f.threat));
  if (!l.length) return false;
  const after = new Set(raw(b).map(f => `${f.slot}|${f.threat}|${f.fn ? f.fn.name : ''}`));
  return l.every(f => !after.has(`${f.slot}|${f.threat}|${f.fn ? f.fn.name : ''}`));
}).length;
const locPairs = pairs.filter(([a]) => raw(a).some(f => localized(a, f) && a.expected_threats.includes(f.threat))).length;
out('## 2. Vulnerable → fixed release');
out('');
out(`${pairs.length} pairs. Verdict improved after the fix in ${better} (${pct(better, pairs.length)}), unchanged in ${pairs.length - better - worse}, worse in ${worse}.`);
out(`Where a localized, threat-matched finding existed, it disappeared in the fixed release in ${locGone}/${locPairs}.`);
out('');
out('| Vulnerable → fixed | Pairs |');
out('|---|---|');
for (const [k, n] of Object.entries(trans).sort((a, b) => b[1] - a[1])) out(`| ${k} | ${n} |`);
out('');

// ── Benign set ────────────────────────────────────────────────────────────────
const B = benign.filter(ok);
const regular = B.filter(r => !r.by_design);
const design = B.filter(r => r.by_design);
const dist = g => ['PASS', 'REVIEW', 'FAIL'].map(v => `${v} ${g.filter(r => r.verdict === v).length}`).join(' · ');
out('## 3. Popular servers (presumed benign)');
out('');
out(`${B.length} servers scanned at HEAD (${benign.length - B.length} could not be ingested).`);
out('');
out(`- Regular servers (${regular.length}): ${dist(regular)} → **false rejection (FAIL) rate ${pct(regular.filter(r => r.verdict === 'FAIL').length, regular.length)}**, review load ${pct(regular.filter(r => r.verdict === 'REVIEW').length, regular.length)}`);
out(`- Command/code execution by design (${design.length}): ${dist(design)}`);
out('');
out('| Server | Verdict | Rules | Top findings |');
out('|---|---|---|---|');
for (const r of B) {
  const top = raw(r).sort((a, b) => b.score - a.score).slice(0, 2).map(f => `${f.slot}:${f.threat} ${f.score.toFixed(2)} (${f.file}${f.fn ? `:${f.fn.name}` : ''})`).join('; ');
  out(`| ${r.id}${r.by_design ? ' *(by design)*' : ''} | ${r.verdict} | ${r.reasons.map(x => x.rule).join(', ') || '—'} | ${top || '—'} |`);
}
out('');

// ── Coverage, errors, timing ─────────────────────────────────────────────────
const all = rows.filter(ok);
const ruleCount = {};
for (const r of all) for (const x of r.reasons) ruleCount[x.rule] = (ruleCount[x.rule] || 0) + 1;
out('## 4. Rules, errors and timing');
out('');
out('| Rule fired | Scans |');
out('|---|---|');
for (const [k, n] of Object.entries(ruleCount).sort((a, b) => b[1] - a[1])) out(`| ${k}${COVERAGE_RULES.has(k) ? ' (coverage)' : ''} | ${n} |`);
out('');
const errs = rows.filter(r => !r.ok);
out(`Ingestion/scan errors: ${errs.length}${errs.length ? '\n\n' + errs.map(r => `- ${r.id} (${r.version}): ${r.error.slice(0, 160)}`).join('\n') : ''}`);
out('');
const secs = all.map(r => r.seconds);
out(`Scan time per server (clone + all analyzers): median ${median(secs).toFixed(1)} s, 95th percentile ${p95(secs).toFixed(1)} s, max ${Math.max(...secs).toFixed(1)} s.`);
out('');

// ── Detail ──────────────────────────────────────────────────────────────────
out('## 5. Per-release detail (vulnerable set)');
out('');
out('| Release | Advisory threat | Verdict | Fixed | Rules | Localized finding |');
out('|---|---|---|---|---|---|');
for (const r of vuln) {
  if (!r.ok) { out(`| ${r.id} | ${r.expected_threats.join(', ')} | ERROR | | ${r.error.slice(0, 60)} | |`); continue; }
  const f = fixed.get(r.id);
  const l = raw(r).filter(x => localized(r, x)).sort((a, b) => b.score - a.score)[0];
  out(`| ${r.id} | ${r.expected_threats.join(', ')} | ${r.verdict} | ${f ? (f.ok ? f.verdict : 'ERR') : '—'} | ${r.reasons.map(x => x.rule).join(', ') || '—'} | ${l ? `${l.slot}:${l.threat} ${l.score.toFixed(2)} ${l.file}${l.fn ? `:${l.fn.name}` : ''}` : '—'} |`);
}
out('');

fs.writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`wrote ${OUT}`);
console.log(lines.slice(0, 40).join('\n'));
